''' Задача 2 — сложный
Есть список:
letters = ["a", "b", "c", "d", "e", "f", "g", "h", "i", "j"]
Нужно срезами:
Получить каждую третью букву начиная с "b".
Получить последние 6 букв в обратном порядке.
Получить все буквы на нечётных позициях, считая с конца. '''

letters = ["a", "b", "c", "d", "e", "f", "g", "h", "i", "j"]
let1 = letters[1::3]
let2 = letters[-6::][::-1]
let3 = letters[::-2]
print(let1)
print(let2)
print(let3)